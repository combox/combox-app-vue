/**
 * Message formatting engine (Telegram-modern parity + standard markdown).
 *
 * Delimiter cheatsheet (documented choice, `__` cannot be both bold and underline):
 *   **bold**   <strong>
 *   __underline__   <u>          (Telegram style: `__` is underline, never bold)
 *   *italic* / _italic_   <em>
 *   ~~strike~~   <s>
 *   ||spoiler||   <span class="mbSpoiler">   (click to reveal)
 *   `inline code`   <code class="mbCode">
 *   [label](https://url)   <a class="mbLink">
 *   @username / bare URLs   autolinked (same regexes as before)
 *
 * Block level:
 *   ```lang ... ```   code block (auto-detect when no language)
 *   > line            blockquote (consecutive lines are grouped)
 *   >>> line >>>      multi-line quote (Telegram style)
 *   - item / 1. item  unordered / ordered list
 *   # .. ######       headings
 *   --- / ***         horizontal rule
 *
 * Safety: every byte of user text is HTML-escaped before it is emitted; only
 * tags generated by this module ever reach the DOM. No user HTML is allowed.
 */

export interface RenderMessageOptions {
  /** Accessible label for the "copy" button on code blocks. */
  copyLabel?: string
}

/** Guard against pathological nested inline recursion. */
const MAX_INLINE_DEPTH = 24

const ESCAPABLE_RE = /[!"#$%&'()*+,\-./:;<=>?@[\\\]^_`{|}~]/
const PUNCT_RE = /[!-/:-@[-`{-~\u00A1-\u00BF\u2010-\u2027\u2030-\u205E]/
const SAFE_HREF_RE = /^(https?:\/\/|mailto:)/i
const LANG_NAME_RE = /^[A-Za-z0-9_+#.-]+$/
const TRAILING_HASH_RE = /[ \t]+#+[ \t]*$/

const FENCE_CLOSE_RE = /^[ \t]*(`{3,}|~{3,})[ \t]*$/
const HR_RE = /^[ \t]{0,3}(-{3,}|\*{3,}|_{3,})[ \t]*$/
const HEADING_RE = /^[ \t]{0,3}(#{1,6})[ \t]+(\S.*?)[ \t]*$/
const QUOTE_MULTI_RE = /^[ \t]{0,3}>>>[ \t]?(.*)$/
const QUOTE_RE = /^[ \t]{0,3}>[ \t]?(.*)$/
const LIST_U_RE = /^[ \t]{0,3}[-*+][ \t]+(.*)$/
const LIST_O_RE = /^[ \t]{0,3}\d{1,9}[.)][ \t]+(.*)$/

